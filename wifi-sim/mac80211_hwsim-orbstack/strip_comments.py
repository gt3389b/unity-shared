"""Normalize a C header for comparison: drop comments, trailing whitespace and
blank lines. OrbStack's /sys/kernel/kheaders.tar.xz is generated by the
kernel's gen_kheaders.sh, which strips comments, so a byte-for-byte diff
against the mainline tarball is all noise. Usage: strip_comments.py FILE..."""
import re
import sys

_COMMENT = re.compile(
    r'//.*?$|/\*.*?\*/|\'(?:\\.|[^\\\'])*\'|"(?:\\.|[^\\"])*"',
    re.DOTALL | re.MULTILINE,
)


def normalize(text: str) -> str:
    def repl(m: re.Match) -> str:
        s = m.group(0)
        return " " if s.startswith(("/", "//")) else s

    text = _COMMENT.sub(repl, text)
    # Collapse runs of blanks too: a comment removed from inside a macro
    # continuation line otherwise leaves a whitespace-only difference.
    lines = (re.sub(r"[ \t]+", " ", l).strip() for l in text.splitlines())
    return "\n".join(l for l in lines if l) + "\n"


def main() -> None:
    for path in sys.argv[1:]:
        with open(path, encoding="utf-8", errors="surrogateescape") as f:
            out = normalize(f.read())
        with open(path, "w", encoding="utf-8", errors="surrogateescape") as f:
            f.write(out)


if __name__ == "__main__":
    main()
